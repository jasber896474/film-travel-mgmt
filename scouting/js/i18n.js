let currentLang = "zh-TW";

function loadLang() {
  const saved = localStorage.getItem(LANG_STORAGE);
  currentLang = LANGS[saved] ? saved : "zh-TW";
  return currentLang;
}

function setLang(lang) {
  currentLang = LANGS[lang] ? lang : "zh-TW";
  localStorage.setItem(LANG_STORAGE, currentLang);
  applyI18n();
}

function t(key, vars) {
  const pack = T[currentLang] || T["zh-TW"];
  let s = pack[key] || T["zh-TW"][key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.replaceAll(`{${k}}`, vars[k]);
    });
  }
  return s;
}

function applyI18n() {
  document.documentElement.lang = currentLang === "zh-CN" ? "zh-CN" : currentLang === "zh-TW" ? "zh-Hant" : currentLang;
  document.title = t("appName");
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
  });
  const sel = document.getElementById("langSelect");
  if (sel) sel.value = currentLang;
}